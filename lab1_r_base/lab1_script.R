# --- 1) Задаём вектор чисел (успеваемость 8 студентов, от 1 до 10) ---
data1 <- c(8, 5, 9, 7, 3, 10, 6, 4)

# --- 2) Переменная data1 уже создана выше ---

# --- 3) Присваиваем имена элементам вектора ---
names(data1) <- c("Иванов", "Петров", "Сидоров", "Козлов",
                   "Новиков", "Фёдоров", "Морозов", "Волков")

# --- 4) Столбиковая диаграмма для data1 ---
barplot(data1,
        main = "Успеваемость студентов",
        col = rainbow(length(data1)),
        ylab = "Оценка",
        las = 2,
        cex.names = 0.8)

# --- 5) Набор строковых переменных data2 (имена студентов) ---
data2 <- c("Алексей", "Борис", "Виктор", "Григорий",
            "Дмитрий", "Евгений", "Жан", "Захар")

# --- 6) Копия диаграммы с легендой и сортировкой по убыванию ---
sorted_data1 <- sort(data1, decreasing = TRUE)
sorted_data2 <- data2[order(data1, decreasing = TRUE)]

barplot(sorted_data1,
        main = "Успеваемость (отсортировано по убыванию)",
        col = rainbow(length(sorted_data1)),
        ylab = "Оценка",
        las = 2,
        cex.names = 0.8)
legend("topright",
       legend = sorted_data2,
       fill = rainbow(length(sorted_data2)),
       cex = 0.7,
       title = "Студенты")

# --- 7) Матрица A размерностью 4x5 ---
A <- matrix(c(2, 5, 8, 1,
              3, 7, 4, 6,
              9, 2, 5, 3,
              1, 8, 6, 4,
              7, 3, 2, 9),
            nrow = 4, ncol = 5)

# --- 8) Мозаичная диаграмма для матрицы A ---
colnames(A) <- paste("Предмет", 1:5)
rownames(A) <- paste("Группа", 1:4)

mosaicplot(A,
           main = "Мозаичная диаграмма матрицы A",
           color = heat.colors(ncol(A)),
           las = 1)

# --- 9) Фрейм данных из data1 и data2 ---
df <- data.frame(Имя = data2, Оценка = as.numeric(data1))
print(df)

# --- 10) Итоговая информация о фрейме ---
summary(df)
